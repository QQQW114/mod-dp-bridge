    private fun validateSnapshotHeader(root: JsonObject, targetMod: String, contents: JsonArray) {
        val gameVersion = root["gameVersion"] as? JsonObject
            ?: throw RuntimeSnapshotMappingException("Runtime snapshot has no gameVersion object.")
        val build = gameVersion.int("build")
        val revision = gameVersion.int("revision")
        if (build != supportedSnapshotBuild || revision != supportedSnapshotRevision) {
            throw RuntimeSnapshotMappingException(
                "Runtime snapshot was captured from build $build revision $revision; " +
                    "this mapper currently requires v$supportedSnapshotBuild.$supportedSnapshotRevision exactly.",
            )
        }
        val loadedMod = root["loadedMod"] as? JsonObject
            ?: throw RuntimeSnapshotMappingException("Runtime snapshot has no loadedMod object.")
        val loadedName = loadedMod.string("name")
        if (loadedName == null || !loadedName.equals(targetMod, ignoreCase = true)) {
            throw RuntimeSnapshotMappingException(
                "Runtime snapshot targetMod '$targetMod' does not match loadedMod '${loadedName ?: "<missing>"}'.",
            )
        }
        root.int("contentCount")?.let { declared ->
            if (declared != contents.size) {
                throw RuntimeSnapshotMappingException(
                    "Runtime snapshot contentCount $declared does not match contents size ${contents.size}.",
                )
            }
        }
    }

    private fun validateContentSnapshots(
        content: JsonObject,
        sourceName: String,
        sourceType: String,
        runtimeClass: String,
        basePath: String,
    ): PhaseValidation {
        val snapshots = content["runtimeSnapshots"] as? JsonObject
            ?: return PhaseValidation.Invalid(
                "RUNTIME_PHASE_SNAPSHOT_INVALID",
                "Runtime content '$sourceName' has no runtimeSnapshots object.",
                "$basePath.runtimeSnapshots",
            )
        val phases = listOf(
            Triple("preContentInit", "PRE_CONTENT_INIT", "$basePath.runtimeSnapshots.preContentInit"),
            Triple("postContentInit", "POST_CONTENT_INIT", "$basePath.runtimeSnapshots.postContentInit"),
            Triple("finalAfterModInit", "FINAL_AFTER_MOD_INIT", "$basePath.runtimeSnapshots.finalAfterModInit"),
        )
        data class PresentPhase(
            val index: Int,
            val key: String,
            val phaseName: String,
            val path: String,
            val snapshot: JsonObject,
            val fields: JsonObject,
        )
        val present = mutableListOf<PresentPhase>()
        phases.forEachIndexed { index, (key, expectedPhase, path) ->
            val raw = snapshots[key]
            if (raw == null || raw is JsonNull) return@forEachIndexed
            val phase = raw as? JsonObject
                ?: return PhaseValidation.Invalid(
                    "RUNTIME_PHASE_SNAPSHOT_INVALID",
                    "Runtime content '$sourceName' has a non-object phase $expectedPhase.",
                    path,
                )
            if (phase.int("schemaVersion") != 1 || phase.string("phase") != expectedPhase ||
                phase.string("name") != sourceName || phase.string("contentType") != sourceType ||
                phase.string("runtimeClass") != runtimeClass
            ) {
                return PhaseValidation.Invalid(
                    "RUNTIME_PHASE_SNAPSHOT_INVALID",
                    "Runtime content '$sourceName' has inconsistent identity metadata in phase $expectedPhase.",
                    path,
                )
            }
            val phaseFields = phase["fields"] as? JsonObject
                ?: return PhaseValidation.Invalid(
                    "RUNTIME_PHASE_SNAPSHOT_INVALID",
                    "Runtime content '$sourceName' phase $expectedPhase has no fields object.",
                    "$path.fields",
                )
            present += PresentPhase(index, key, expectedPhase, path, phase, phaseFields)
        }
        if (present.none { it.key == "finalAfterModInit" }) {
            return PhaseValidation.Invalid(
                "RUNTIME_PHASE_SNAPSHOT_INVALID",
                "Runtime content '$sourceName' is missing the authoritative FINAL_AFTER_MOD_INIT phase.",
                "$basePath.runtimeSnapshots.finalAfterModInit",
            )
        }
        val firstIndex = present.first().index
        if (present.map { it.index } != (firstIndex..phases.lastIndex).toList()) {
            return PhaseValidation.Invalid(
                "RUNTIME_PHASE_PRESENCE_NON_MONOTONIC",
                "Runtime content '$sourceName' appears in a phase, disappears, and later reappears.",
                "$basePath.runtimeSnapshots",
                present.joinToString { it.phaseName },
            )
        }
        if (present.drop(1).any { it.fields.keys != present.first().fields.keys }) {
            return PhaseValidation.Invalid(
                "RUNTIME_PHASE_FIELD_SET_MISMATCH",
                "Runtime content '$sourceName' does not expose the same field set in every phase where it exists.",
                "$basePath.runtimeSnapshots",
                present.joinToString("; ") { "${it.phaseName}=${it.fields.keys.sorted()}" },
            )
        }
        val authoritative = present.first()
        return PhaseValidation.Valid(
            authoritative = authoritative.snapshot,
            authoritativeFields = authoritative.fields,
            authoritativeKey = authoritative.key,
            authoritativePhase = authoritative.phaseName,
        )
    }

