    private fun buildExecutableFileResults(
        provenanceIndex: JarProvenanceIndex,
        contents: JsonArray,
        contentResults: List<RuntimePreparedContentResult>,
        targetMod: String,
        preparedFiles: List<RuntimePreparedFile>,
    ): List<RuntimePreparedFileResult> {
        val emittedSources = preparedFiles.flatMapTo(hashSetOf()) { it.sourcePaths }
        val unsupportedSources = hashSetOf<String>()
        contents.forEachIndexed { index, element ->
            val content = element as? JsonObject ?: return@forEachIndexed
            if (content.string("modName")?.equals(targetMod, ignoreCase = true) != true) return@forEachIndexed
            val disposition = contentResults.getOrNull(index)?.disposition ?: return@forEachIndexed
            if (disposition == ContentDisposition.UNSUPPORTED || disposition == ContentDisposition.FAILED) {
                provenanceIndex.forContent(content)?.let(unsupportedSources::add)
            }
        }
        return provenanceIndex.executableEntries.asSequence()
            .filterNot { it in emittedSources }
            .map { sourcePath ->
                val unsupported = sourcePath in unsupportedSources || provenanceIndex.isDynamicExecutable(sourcePath)
                RuntimePreparedFileResult(
                    sourcePath = sourcePath,
                    status = if (unsupported) ConvertedFileStatus.UNSUPPORTED else ConvertedFileStatus.EXCLUDED,
                    reason = if (unsupported) {
                        "The release Mod was executed, but this executable entry was not directly representable in the current v159.7 mapper milestone."
                    } else {
                        "The release Mod was executed; this helper/source entry had no direct emitted declaration or selected runtime asset."
                    },
                    diagnosticCodes = listOf(
                        if (unsupported) "RUNTIME_EXECUTABLE_NOT_MAPPED" else "RUNTIME_EXECUTABLE_NO_DIRECT_OUTPUT",
                    ),
                )
            }
            .sortedBy { it.sourcePath }
            .toList()
    }

