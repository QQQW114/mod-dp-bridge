    private fun compactTypedValue(value: JsonElement): String {
        val objectValue = value as? JsonObject ?: return value.toString().take(200)
        return when (objectValue.string("kind")) {
            "number", "string", "enum" -> objectValue.string("value") ?: objectValue.toString().take(200)
            "boolean" -> objectValue["value"]?.toString() ?: "?"
            "color" -> objectValue.string("rgba") ?: "?"
            "contentRef" -> objectValue.string("name") ?: "?"
            "staticRef" -> objectValue.string("parserValue") ?: objectValue.string("field") ?: "?"
            "null" -> "null"
            else -> objectValue.toString().take(200)
        }
    }

    private fun sha256(path: Path): String {
        val digest = MessageDigest.getInstance("SHA-256")
        Files.newInputStream(path).use { input ->
            val buffer = ByteArray(DEFAULT_BUFFER_SIZE)
            while (true) {
                val read = input.read(buffer)
                if (read < 0) break
                digest.update(buffer, 0, read)
            }
        }
        return digest.digest().joinToString("") { "%02x".format(it) }
    }

