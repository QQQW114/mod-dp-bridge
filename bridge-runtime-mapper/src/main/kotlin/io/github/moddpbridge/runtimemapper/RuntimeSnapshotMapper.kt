    private data class JarProvenanceIndex(
        val entries: List<String>,
        val resolvedRoot: String?,
    ) {
        val executableEntries: List<String> = entries.filter(::looksExecutable)

        fun forContent(content: JsonObject): String? {
            val runtimeClass = content.string("runtimeClass")
            if (runtimeClass != null) {
                val classPath = runtimeClass.replace('.', '/') + ".class"
                entries.firstOrNull { it.equals(classPath, ignoreCase = true) }?.let { return it }
                entries.firstOrNull { it.endsWith("/$classPath", ignoreCase = true) }?.let { return it }
            }

            val stackClasses = (content["registrationStack"] as? JsonArray).orEmpty().mapNotNull { frame ->
                (frame as? JsonPrimitive)?.contentOrNull?.substringBefore('(')?.substringBeforeLast('.')
            }.filterNot { className ->
                className.startsWith("mindustry.") || className.startsWith("arc.") ||
                    className.startsWith("java.") || className.startsWith("javax.")
            }
            stackClasses.forEach { className ->
                val classPath = className.replace('.', '/') + ".class"
                entries.firstOrNull { it.equals(classPath, ignoreCase = true) }?.let { return it }
                entries.firstOrNull { it.endsWith("/$classPath", ignoreCase = true) }?.let { return it }
            }
            return null
        }

        fun isDynamicExecutable(path: String): Boolean {
            val relative = relative(path)
            val extension = relative.substringAfterLast('.', "").lowercase(Locale.ROOT)
            return extension in setOf("dex", "jar", "js", "kts") ||
                relative.startsWith("scripts/", ignoreCase = true) ||
                relative.startsWith("assets/scripts/", ignoreCase = true)
        }

        private fun looksExecutable(path: String): Boolean {
            val relative = relative(path)
            if (relative.startsWith("assets/", ignoreCase = true) &&
                !relative.startsWith("assets/scripts/", ignoreCase = true)
            ) return false
            if (relative.equals("gradle/wrapper/gradle-wrapper.jar", ignoreCase = true)) return false
            val extension = relative.substringAfterLast('.', "").lowercase(Locale.ROOT)
            return extension in setOf("class", "jar", "dex", "js", "kts", "java", "kt") ||
                relative.startsWith("scripts/", ignoreCase = true) ||
                relative.startsWith("assets/scripts/", ignoreCase = true)
        }

        private fun relative(path: String): String =
            resolvedRoot?.let { path.removePrefix("$it/") } ?: path

        companion object {
            fun read(jar: Path): JarProvenanceIndex {
                val entries = ZipFile(jar.toFile()).use { zip ->
                    zip.entries().asSequence()
                        .filterNot { it.isDirectory }
                        .map { entry ->
                            val replaced = entry.name.replace('\\', '/')
                            val parts = replaced.split('/')
                            if (replaced.startsWith('/') || ':' in replaced || '\u0000' in replaced ||
                                parts.any { it.isBlank() || it == "." || it == ".." }
                            ) {
                                throw RuntimeSnapshotMappingException("Unsafe release-JAR entry path: ${entry.name}")
                            }
                            parts.joinToString("/")
                        }
                        .filter(String::isNotBlank)
                        .take(100_001)
                        .toList()
                }
                if (entries.size > 100_000) {
                    throw RuntimeSnapshotMappingException("Release JAR contains more than 100000 file entries.")
                }
                val roots = entries.filter { '/' in it }.map { it.substringBefore('/') }.distinct()
                val reserved = setOf("assets", "content", "patches", "sprites", "sounds", "music", "bundles", "meta-inf")
                val root = roots.singleOrNull()?.takeIf { candidate ->
                    entries.all { it.startsWith("$candidate/") } && candidate.lowercase(Locale.ROOT) !in reserved
                }
                return JarProvenanceIndex(entries.sorted(), root)
            }
        }
    }

