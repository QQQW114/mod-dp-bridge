/** Mapping policy for the first runtime-snapshot-to-v159.7 milestone. */
data class RuntimeSnapshotMappingOptions(
    val includeAssets: Boolean = true,
    /** May only narrow the mapper's built-in milestone; it cannot enable unfinished content kinds. */
    val supportedContentTypes: Set<String> = setOf("item", "liquid", "status"),
)

data class RuntimeSnapshotMappingSummary(
    val snapshotSchemaVersion: Int,
    val targetMod: String,
    val observedContents: Int,
    val convertedContents: Int,
    val degradedContents: Int,
    val excludedContents: Int,
    val unsupportedContents: Int,
    val failedContents: Int,
    val generatedContentFiles: Int,
    val selectedAssetFiles: Int,
    val mappedFields: Int,
    val omittedNullFields: Int,
    val droppedFields: Int,
)

/**
 * Inert result of mapping a retained runtime snapshot. [prepared] contains only JSON/HJSON bytes
 * generated by this module and exact release-JAR asset references; no Mod classes are retained.
 */
data class RuntimeSnapshotMappingResult(
    val prepared: RuntimePreparedConversion,
    val summary: RuntimeSnapshotMappingSummary,
    val reportJson: String,
)

class RuntimeSnapshotMappingException(message: String, cause: Throwable? = null) : RuntimeException(message, cause)

/** Maps typed runtime snapshot schema v2 into the v159.7 DataPatcher declarative subset. */
object RuntimeSnapshotMapper {
    private const val supportedSnapshotSchema = 2
    private const val supportedSnapshotBuild = 159
    private const val supportedSnapshotRevision = 7
    private const val maxSnapshotBytes = 128L * 1024L * 1024L
    private val implementedContentTypes = setOf("item", "liquid", "status")
    private val json = Json {
        prettyPrint = true
        prettyPrintIndent = "  "
        explicitNulls = false
        ignoreUnknownKeys = true
    }

    fun prepare(
        snapshot: Path,
        modJar: Path,
        options: RuntimeSnapshotMappingOptions = RuntimeSnapshotMappingOptions(),
    ): RuntimeSnapshotMappingResult {
        val snapshotPath = snapshot.toAbsolutePath().normalize()
        val jarPath = modJar.toAbsolutePath().normalize()
        require(Files.isRegularFile(snapshotPath)) { "Runtime snapshot does not exist: $snapshotPath" }
        require(Files.isRegularFile(jarPath)) { "Release Mod JAR does not exist: $jarPath" }
        require(options.supportedContentTypes.all { it in implementedContentTypes }) {
            "supportedContentTypes may only narrow ${implementedContentTypes.sorted()}; " +
                "unfinished content mappings cannot be enabled by an option."
        }
        if (Files.size(snapshotPath) > maxSnapshotBytes) {
            throw RuntimeSnapshotMappingException(
                "Runtime snapshot exceeds the $maxSnapshotBytes byte safety limit: $snapshotPath",
            )
        }

        val root = try {
            json.parseToJsonElement(Files.readString(snapshotPath, StandardCharsets.UTF_8)).jsonObject
        } catch (error: Throwable) {
            throw RuntimeSnapshotMappingException("Could not parse runtime snapshot: $snapshotPath", error)
        }
        val schemaVersion = root.int("schemaVersion")
            ?: throw RuntimeSnapshotMappingException("Runtime snapshot has no integer schemaVersion.")
        if (schemaVersion != supportedSnapshotSchema) {
            throw RuntimeSnapshotMappingException(
                "Runtime snapshot schema $schemaVersion is unsupported; expected $supportedSnapshotSchema.",
            )
        }
        val targetMod = root.string("targetMod")?.takeIf(String::isNotBlank)
            ?: throw RuntimeSnapshotMappingException("Runtime snapshot has no targetMod.")
        val contents = root["contents"] as? JsonArray
            ?: throw RuntimeSnapshotMappingException("Runtime snapshot has no contents array.")
        validateSnapshotHeader(root, targetMod, contents)

        val provenanceIndex = try {
            JarProvenanceIndex.read(jarPath)
        } catch (error: Throwable) {
            throw RuntimeSnapshotMappingException("Could not index release-JAR provenance: $jarPath", error)
        }

        val diagnostics = mutableListOf<Diagnostic>()
        val logs = mutableListOf<String>()
        val preparedFiles = mutableListOf<RuntimePreparedFile>()
        val contentResults = mutableListOf<RuntimePreparedContentResult>()
        val fieldOutcomes = mutableListOf<FieldOutcome>()
        val phaseDifferences = mutableListOf<PhaseDifference>()
        val seenOutputPaths = hashSetOf<String>()

        logs += "Mapping runtime snapshot schema $schemaVersion for Mod '$targetMod'."
        contents.forEachIndexed { index, element ->
            val content = element as? JsonObject
            if (content == null) {
                diagnostics += diagnostic(
                    code = "RUNTIME_CONTENT_RECORD_INVALID",
                    severity = DiagnosticSeverity.ERROR,
                    message = "Runtime content record $index is not an object.",
                    snapshotPath = snapshotPath,
                    jsonPath = "$.contents[$index]",
                )
                contentResults += RuntimePreparedContentResult(
                    sourceSymbol = "<contents[$index]>",
                    disposition = ContentDisposition.FAILED,
                    reason = "Runtime snapshot record is not an object.",
                    diagnosticCodes = listOf("RUNTIME_CONTENT_RECORD_INVALID"),
                    location = SourceLocation(snapshotPath.toString(), "$.contents[$index]"),
                )
                return@forEachIndexed
            }
            val filesBefore = preparedFiles.size
            val resultsBefore = contentResults.size
            val diagnosticsBefore = diagnostics.size
            val fieldsBefore = fieldOutcomes.size
            val differencesBefore = phaseDifferences.size
            val pathsBefore = seenOutputPaths.toSet()
            try {
                mapContent(
                    content = content,
                    index = index,
                    targetMod = targetMod,
                    snapshotPath = snapshotPath,
                    options = options,
                    preparedFiles = preparedFiles,
                    contentResults = contentResults,
                    diagnostics = diagnostics,
                    fieldOutcomes = fieldOutcomes,
                    phaseDifferences = phaseDifferences,
                    seenOutputPaths = seenOutputPaths,
                    provenanceIndex = provenanceIndex,
                )
            } catch (error: Exception) {
                preparedFiles.truncate(filesBefore)
                contentResults.truncate(resultsBefore)
                diagnostics.truncate(diagnosticsBefore)
                fieldOutcomes.truncate(fieldsBefore)
                phaseDifferences.truncate(differencesBefore)
                seenOutputPaths.retainAll(pathsBefore)
                val sourceName = content.string("name") ?: "<contents[$index]>"
                diagnostics += diagnostic(
                    code = "RUNTIME_CONTENT_MAPPING_FAILED",
                    severity = DiagnosticSeverity.ERROR,
                    message = "Runtime content '$sourceName' could not be mapped safely.",
                    snapshotPath = snapshotPath,
                    jsonPath = "$.contents[$index]",
                    details = "${error::class.java.name}: ${error.message ?: "no message"}",
                )
                contentResults += RuntimePreparedContentResult(
                    sourceSymbol = sourceName,
                    disposition = ContentDisposition.FAILED,
                    sourceType = content.string("contentType"),
                    reason = "The mapper rejected an invalid or inconsistent runtime record.",
                    diagnosticCodes = listOf("RUNTIME_CONTENT_MAPPING_FAILED"),
                    location = SourceLocation(snapshotPath.toString(), "$.contents[$index]"),
                )
            }
        }

        var assetSnapshot: RuntimeAssetSnapshot? = null
        if (options.includeAssets) {
            assetSnapshot = try {
                RuntimeAssetStager.scanForRuntimeMapper(jarPath)
            } catch (error: Throwable) {
                throw RuntimeSnapshotMappingException("Runtime asset staging failed for $jarPath: ${error.message}", error)
            }
            assetSnapshot.diagnostics.forEach { diagnostics += it.toModelDiagnostic(jarPath) }
            assetSnapshot.files.forEach { asset ->
                preparedFiles += RuntimePreparedFile(
                    outputPath = asset.outputPath,
                    sourcePaths = listOf(asset.sourceEntryPath),
                    bytes = null,
                    namespace = RuntimePreparedOutputNamespace.SOURCE,
                    reason = "Exact runtime-loadable ${asset.kind.name.lowercase()} asset selected from the release JAR.",
                )
            }
            logs += "Selected ${assetSnapshot.files.size} exact release-JAR assets " +
                "(${assetSnapshot.stagedBytes} bytes, staging SHA-256 ${assetSnapshot.stagingSha256})."
        } else {
            logs += "Runtime asset staging was disabled by the caller."
        }

        val executableFileResults = buildExecutableFileResults(
            provenanceIndex = provenanceIndex,
            contents = contents,
            contentResults = contentResults,
            targetMod = targetMod,
            preparedFiles = preparedFiles,
        )
        logs += "Assigned explicit outcomes to ${executableFileResults.size} executable release-JAR entries " +
            "that did not directly produce an emitted file."

        phaseDifferences.forEach { difference ->
            diagnostics += diagnostic(
                code = "RUNTIME_PHASE_VALUE_CHANGED",
                severity = DiagnosticSeverity.INFO,
                message = "A mapped field changed after the ${difference.authoritativePhase} snapshot; " +
                    "the earliest available registration snapshot remains authoritative.",
                snapshotPath = snapshotPath,
                jsonPath = difference.jsonPath,
                details = "${difference.contentName}.${difference.field}: ${difference.phases.joinToString()}",
                suggestion = "If v159.7 validation or gameplay differs, inspect whether this was a base init derivation or custom Mod code.",
            )
        }

        val converted = contentResults.count { it.disposition == ContentDisposition.CONVERTED }
        val degraded = contentResults.count { it.disposition == ContentDisposition.DEGRADED }
        val excluded = contentResults.count { it.disposition == ContentDisposition.EXCLUDED }
        val unsupported = contentResults.count { it.disposition == ContentDisposition.UNSUPPORTED }
        val failed = contentResults.count { it.disposition == ContentDisposition.FAILED }
        val generatedContentFiles = preparedFiles.count { it.outputPath.startsWith("content/") }
        val summary = RuntimeSnapshotMappingSummary(
            snapshotSchemaVersion = schemaVersion,
            targetMod = targetMod,
            observedContents = contents.size,
            convertedContents = converted,
            degradedContents = degraded,
            excludedContents = excluded,
            unsupportedContents = unsupported,
            failedContents = failed,
            generatedContentFiles = generatedContentFiles,
            selectedAssetFiles = assetSnapshot?.files?.size ?: 0,
            mappedFields = fieldOutcomes.count { it.disposition == FieldDisposition.MAPPED },
            omittedNullFields = fieldOutcomes.count { it.disposition == FieldDisposition.OMITTED_NULL },
            droppedFields = fieldOutcomes.count { it.disposition == FieldDisposition.DROPPED },
        )
        logs += "Runtime mapper emitted $generatedContentFiles content declarations: " +
            "$converted converted, $degraded degraded; $excluded excluded, $unsupported unsupported, and $failed failed records were not emitted."

        val metadata = buildMap {
            put("runtimeSnapshotSchema", schemaVersion.toString())
            put("runtimeTargetMod", targetMod)
            put("runtimeSnapshotSha256", sha256(snapshotPath))
            put("runtimeObservedContents", contents.size.toString())
            put("runtimeGeneratedContents", generatedContentFiles.toString())
            put("runtimeConvertedContents", converted.toString())
            put("runtimeDegradedContents", degraded.toString())
            put("runtimeExcludedContents", excluded.toString())
            put("runtimeUnsupportedContents", unsupported.toString())
            put("runtimeFailedContents", failed.toString())
            put("runtimeMappedFields", summary.mappedFields.toString())
            put("runtimeDroppedFields", summary.droppedFields.toString())
            put("runtimeReleaseJarSha256", sha256(jarPath))
            put("runtimeExecutableOutcomes", executableFileResults.size.toString())
            assetSnapshot?.let {
                put("runtimeSelectedAssets", it.files.size.toString())
                put("runtimeAssetStagingSha256", it.stagingSha256)
            }
        }
        val prepared = RuntimePreparedConversion(
            files = preparedFiles.sortedBy { it.outputPath.lowercase(Locale.ROOT) },
            fileResults = executableFileResults,
            contentResults = contentResults,
            diagnostics = diagnostics,
            logs = logs,
            metadata = metadata,
            replaceOriginalContent = true,
        )
        return RuntimeSnapshotMappingResult(
            prepared = prepared,
            summary = summary,
            reportJson = buildReport(
                snapshotPath = snapshotPath,
                jarPath = jarPath,
                summary = summary,
                contentResults = contentResults,
                fieldOutcomes = fieldOutcomes,
                phaseDifferences = phaseDifferences,
                diagnostics = diagnostics,
                assetSnapshot = assetSnapshot,
            ),
        )
    }

    private fun mapContent(
        content: JsonObject,
        index: Int,
        targetMod: String,
        snapshotPath: Path,
        options: RuntimeSnapshotMappingOptions,
        preparedFiles: MutableList<RuntimePreparedFile>,
        contentResults: MutableList<RuntimePreparedContentResult>,
        diagnostics: MutableList<Diagnostic>,
        fieldOutcomes: MutableList<FieldOutcome>,
        phaseDifferences: MutableList<PhaseDifference>,
        seenOutputPaths: MutableSet<String>,
        provenanceIndex: JarProvenanceIndex,
    ) {
        val basePath = "$.contents[$index]"
        val sourceName = content.string("name")?.takeIf(String::isNotBlank) ?: "<contents[$index]>"
        val sourceType = content.string("contentType")
        val kind = sourceType?.let(::contentKind)
        val owner = content.string("modName")
        if (owner == null) {
            addFailedContent(
                sourceName, kind, sourceType, "RUNTIME_CONTENT_OWNER_MISSING",
                "Runtime content '$sourceName' has no owning Mod identity.", basePath, snapshotPath,
                diagnostics, contentResults,
            )
            return
        }
        if (!owner.equals(targetMod, ignoreCase = true)) {
            contentResults += RuntimePreparedContentResult(
                sourceSymbol = sourceName,
                kind = kind,
                disposition = ContentDisposition.EXCLUDED,
                sourceType = sourceType,
                reason = "The registration belongs to dependency Mod '$owner', not target Mod '$targetMod'.",
                diagnosticCodes = listOf("DEPENDENCY_CONTENT_EXCLUDED"),
                location = SourceLocation(snapshotPath.toString(), basePath),
            )
            return
        }
        if (sourceType == null || sourceType !in options.supportedContentTypes || sourceType !in implementedContentTypes || kind == null) {
            contentResults += RuntimePreparedContentResult(
                sourceSymbol = sourceName,
                kind = kind,
                disposition = ContentDisposition.UNSUPPORTED,
                sourceType = sourceType,
                reason = "Content type '${sourceType ?: "unknown"}' is outside the current runtime mapper milestone.",
                diagnosticCodes = listOf("RUNTIME_CONTENT_TYPE_NOT_MAPPED"),
                location = SourceLocation(snapshotPath.toString(), basePath),
            )
            diagnostics += diagnostic(
                code = "RUNTIME_CONTENT_TYPE_NOT_MAPPED",
                severity = DiagnosticSeverity.WARNING,
                message = "Runtime content '$sourceName' (${sourceType ?: "unknown"}) was retained in the report but not emitted.",
                snapshotPath = snapshotPath,
                jsonPath = basePath,
                suggestion = "Unit/weapon and block/factory mappings are subsequent milestones.",
            )
            return
        }

        val runtimeClass = content.string("runtimeClass")?.takeIf(String::isNotBlank)
        if (runtimeClass == null) {
            addFailedContent(
                sourceName, kind, sourceType, "RUNTIME_CONTENT_CLASS_MISSING",
                "Runtime content '$sourceName' has no runtimeClass.", "$basePath.runtimeClass", snapshotPath,
                diagnostics, contentResults,
            )
            return
        }

        val localName = localContentName(sourceName, targetMod)
        if (!validLocalName(localName)) {
            diagnostics += diagnostic(
                code = "RUNTIME_CONTENT_NAME_INVALID",
                severity = DiagnosticSeverity.ERROR,
                message = "Runtime content '$sourceName' cannot be represented as a safe DP content basename.",
                snapshotPath = snapshotPath,
                jsonPath = "$basePath.name",
            )
            contentResults += RuntimePreparedContentResult(
                sourceSymbol = sourceName,
                kind = kind,
                disposition = ContentDisposition.FAILED,
                sourceType = sourceType,
                reason = "Unsafe or empty local content name '$localName'.",
                diagnosticCodes = listOf("RUNTIME_CONTENT_NAME_INVALID"),
                location = SourceLocation(snapshotPath.toString(), "$basePath.name"),
            )
            return
        }
        val outputPath = "content/${kind.folderName}/$localName.hjson"

        val provenance = provenanceIndex.forContent(content)
        if (provenance == null) {
            diagnostics += diagnostic(
                code = "RUNTIME_CONTENT_PROVENANCE_MISSING",
                severity = DiagnosticSeverity.ERROR,
                message = "No exact release-JAR runtimeClass or registration-stack class can substantiate runtime content '$sourceName'.",
                snapshotPath = snapshotPath,
                jsonPath = basePath,
                suggestion = "Verify that the snapshot and release JAR are from the same build.",
            )
            contentResults += RuntimePreparedContentResult(
                sourceSymbol = sourceName,
                kind = kind,
                disposition = ContentDisposition.FAILED,
                sourceType = sourceType,
                reason = "Snapshot/JAR provenance could not be linked.",
                diagnosticCodes = listOf("RUNTIME_CONTENT_PROVENANCE_MISSING"),
                location = SourceLocation(snapshotPath.toString(), basePath),
            )
            return
        }

        val phaseResult = validateContentSnapshots(content, sourceName, sourceType, runtimeClass, basePath)
        if (phaseResult is PhaseValidation.Invalid) {
            diagnostics += diagnostic(
                code = phaseResult.code,
                severity = DiagnosticSeverity.ERROR,
                message = phaseResult.message,
                snapshotPath = snapshotPath,
                jsonPath = phaseResult.jsonPath,
                details = phaseResult.details,
            )
            contentResults += RuntimePreparedContentResult(
                sourceSymbol = sourceName,
                kind = kind,
                disposition = ContentDisposition.FAILED,
                sourceType = sourceType,
                reason = "The three-phase runtime snapshot contract is incomplete or inconsistent.",
                diagnosticCodes = listOf(phaseResult.code),
                location = SourceLocation(snapshotPath.toString(), phaseResult.jsonPath),
            )
            return
        }
        phaseResult as PhaseValidation.Valid
        val authoritative = phaseResult.authoritative
        val fields = phaseResult.authoritativeFields
        val authoritativePath = "$basePath.runtimeSnapshots.${phaseResult.authoritativeKey}"

        val output = linkedMapOf<String, JsonElement>()
        val contentDiagnosticCodes = linkedSetOf<String>()
        val targetType = resolveTargetParser(
            sourceType,
            authoritative,
            phaseResult.authoritativeKey,
            output,
            diagnostics,
            contentDiagnosticCodes,
            snapshotPath,
            basePath,
        )
        var degraded = targetType.degraded
        if (phaseResult.authoritativePhase != "PRE_CONTENT_INIT") {
            degraded = true
            contentDiagnosticCodes += "RUNTIME_CONTENT_REGISTERED_LATE"
            diagnostics += diagnostic(
                code = "RUNTIME_CONTENT_REGISTERED_LATE",
                severity = DiagnosticSeverity.WARNING,
                message = "Runtime content '$sourceName' was first observed in ${phaseResult.authoritativePhase}; " +
                    "that later snapshot was used because no PRE_CONTENT_INIT registration exists.",
                snapshotPath = snapshotPath,
                jsonPath = authoritativePath,
                suggestion = "Review fields derived by init/event handlers; DataPatcher validation proves loadability, not behavioral equivalence.",
            )
        }
        val fieldSpecs = fieldSpecs(sourceType, targetType.parserName)
        val missingFields = fieldSpecs.keys - fields.keys
        if (missingFields.isNotEmpty()) {
            addFailedContent(
                sourceName, kind, sourceType, "RUNTIME_REQUIRED_FIELDS_MISSING",
                "Runtime content '$sourceName' is missing required schema-v2 fields.",
                "$authoritativePath.fields", snapshotPath, diagnostics, contentResults,
                details = missingFields.sorted().joinToString(),
            )
            return
        }
        fields.forEach { (field, typed) ->
            val fieldPath = "$authoritativePath.fields.$field"
            val spec = fieldSpecs[field]
            val conversion = if (spec == null) {
                ValueConversion.Dropped(
                    runtimeKind(typed),
                    "RUNTIME_FIELD_NOT_ALLOWED",
                    "Field '$field' is not in the fixed v159.7 $sourceType/${targetType.parserName} mapper schema.",
                )
            } else {
                convertTypedValue(typed, fieldPath, spec)
            }
            when (conversion) {
                is ValueConversion.Mapped -> {
                    output[field] = conversion.value
                    fieldOutcomes += FieldOutcome(sourceName, field, FieldDisposition.MAPPED, conversion.kind, null, fieldPath)
                }
                ValueConversion.Null -> {
                    fieldOutcomes += FieldOutcome(sourceName, field, FieldDisposition.OMITTED_NULL, "null", "Null values use the target default.", fieldPath)
                }
                is ValueConversion.Dropped -> {
                    degraded = true
                    contentDiagnosticCodes += conversion.code
                    fieldOutcomes += FieldOutcome(sourceName, field, FieldDisposition.DROPPED, conversion.kind, conversion.reason, fieldPath)
                    diagnostics += diagnostic(
                        code = conversion.code,
                        severity = DiagnosticSeverity.WARNING,
                        message = "Runtime field '$sourceName.$field' was not serialized into DP HJSON.",
                        snapshotPath = snapshotPath,
                        jsonPath = fieldPath,
                        details = conversion.reason,
                        suggestion = "Add a manual v159.7-compatible field/effect when this changes map gameplay.",
                    )
                }
            }
        }

        val behaviorLosses = collectBehaviorLosses(
            authoritative,
            phaseResult.authoritativeKey,
            sourceName,
            snapshotPath,
            basePath,
            diagnostics,
        )
        if (behaviorLosses.isNotEmpty()) {
            degraded = true
            contentDiagnosticCodes += behaviorLosses
        }
        collectPhaseDifferences(
            content,
            sourceName,
            basePath,
            phaseResult.authoritativeKey,
            phaseResult.authoritativePhase,
            fields,
            output.keys,
            phaseDifferences,
        )

        if (!seenOutputPaths.add(outputPath.lowercase(Locale.ROOT))) {
            addFailedContent(
                sourceName, kind, sourceType, "RUNTIME_CONTENT_NAME_COLLISION",
                "Multiple runtime registrations map to '$outputPath'.", basePath, snapshotPath,
                diagnostics, contentResults,
            )
            return
        }

        val hjson = json.encodeToString(JsonObject(output)) + "\n"
        preparedFiles += RuntimePreparedFile(
            outputPath = outputPath,
            sourcePaths = listOf(provenance),
            bytes = hjson.toByteArray(StandardCharsets.UTF_8),
            namespace = RuntimePreparedOutputNamespace.SOURCE,
            reason = "Generated from ${phaseResult.authoritativePhase} typed runtime fields for '$sourceName'.",
        )
        contentResults += RuntimePreparedContentResult(
            sourceSymbol = sourceName,
            kind = kind,
            disposition = if (degraded) ContentDisposition.DEGRADED else ContentDisposition.CONVERTED,
            sourceType = runtimeClass,
            targetType = targetType.parserName,
            outputName = "dp-$localName",
            outputPath = outputPath,
            reason = if (degraded) {
                "Loadable base fields were emitted; custom/opaque behavior remains explicitly reported."
            } else {
                "All captured ${phaseResult.authoritativePhase} fields were representable in v159.7 DP HJSON."
            },
            diagnosticCodes = contentDiagnosticCodes.toList(),
            location = SourceLocation(snapshotPath.toString(), basePath),
        )
    }

    private fun resolveTargetParser(
        sourceType: String,
        authoritative: JsonObject,
        authoritativeKey: String,
        output: MutableMap<String, JsonElement>,
        diagnostics: MutableList<Diagnostic>,
        codes: MutableSet<String>,
        snapshotPath: Path,
        basePath: String,
    ): TargetParserDecision {
        val canonical = canonicalParserName(sourceType)
        val fallback = authoritative["sourceClassMapFallback"] as? JsonObject
        val parserName = fallback?.string("parserName")
        val loadableRoot = (fallback?.get("loadableRoot") as? JsonPrimitive)?.booleanOrNull
        val allowed = allowedParserNames.getValue(sourceType)
        if (parserName == null || loadableRoot != true || parserName !in allowed || !SAFE_PARSER_NAME.matches(parserName)) {
            val code = "RUNTIME_CLASS_FALLBACK_UNLOADABLE"
            codes += code
            diagnostics += diagnostic(
                code = code,
                severity = DiagnosticSeverity.WARNING,
                message = "The observed runtime class fallback is not an approved v159.7 $sourceType parser; base $canonical is used.",
                snapshotPath = snapshotPath,
                jsonPath = "$basePath.runtimeSnapshots.$authoritativeKey.sourceClassMapFallback",
                details = "parserName=${parserName ?: "<missing>"}, loadableRoot=${loadableRoot ?: "<invalid>"}, allowed=${allowed.sorted()}",
            )
            return TargetParserDecision(canonical, degraded = true)
        }
        if (parserName != canonical) output["type"] = JsonPrimitive(parserName)
        return TargetParserDecision(parserName, degraded = false)
    }

    private fun convertTypedValue(element: JsonElement, jsonPath: String, spec: FieldSpec): ValueConversion {
        val value = element as? JsonObject
            ?: return ValueConversion.Dropped("unknown", "RUNTIME_TYPED_VALUE_INVALID", "Typed value is not an object at $jsonPath.")
        val declaredType = value.string("declaredType")
            ?: return ValueConversion.Dropped("unknown", "RUNTIME_TYPED_VALUE_INVALID", "Typed value has no declaredType.")
        val kind = value.string("kind")
            ?: return ValueConversion.Dropped("unknown", "RUNTIME_TYPED_VALUE_INVALID", "Typed value has no kind discriminator.")
        if (kind != "null" && kind !in spec.kinds) {
            return ValueConversion.Dropped(
                kind,
                "RUNTIME_FIELD_KIND_MISMATCH",
                "Runtime kind '$kind' (declaredType=$declaredType) is not allowed; expected ${spec.kinds.sorted()}.",
            )
        }
        return when (kind) {
            "null" -> ValueConversion.Null
            "boolean" -> (value["value"] as? JsonPrimitive)?.booleanOrNull?.let {
                ValueConversion.Mapped(JsonPrimitive(it), kind)
            } ?: ValueConversion.Dropped(kind, "RUNTIME_TYPED_VALUE_INVALID", "Boolean value is missing or invalid.")
            "number" -> {
                val numberType = value.string("numberType")
                if (numberType !in spec.numberTypes) {
                    ValueConversion.Dropped(
                        kind,
                        "RUNTIME_NUMBER_TYPE_MISMATCH",
                        "numberType '${numberType ?: "<missing>"}' is not allowed; expected ${spec.numberTypes.sorted()}.",
                    )
                } else {
                    numberValue(value.string("value"), numberType)
                }
            }
            "string", "enum" -> value.string("value")?.let { ValueConversion.Mapped(JsonPrimitive(it), kind) }
                ?: ValueConversion.Dropped(kind, "RUNTIME_TYPED_VALUE_INVALID", "String/enum value is missing.")
            "color" -> value.string("rgba")?.takeIf { it.matches(COLOR) }?.let {
                ValueConversion.Mapped(JsonPrimitive(it.lowercase(Locale.ROOT)), kind)
            } ?: ValueConversion.Dropped(kind, "RUNTIME_COLOR_INVALID", "RGBA value is absent or not 8 hexadecimal digits.")
            "contentRef" -> {
                val name = value.string("name")?.takeIf(::validReferenceName)
                val contentType = value.string("contentType")
                if (name == null || contentType != spec.contentReferenceType) {
                    ValueConversion.Dropped(
                        kind,
                        "RUNTIME_CONTENT_REFERENCE_INVALID",
                        "Content reference name/type is invalid: name=${name ?: "<invalid>"}, type=${contentType ?: "<missing>"}, expected=${spec.contentReferenceType}.",
                    )
                } else {
                    ValueConversion.Mapped(JsonPrimitive(name), kind)
                }
            }
            "staticRef" -> {
                val owner = value.string("owner")
                val field = value.string("field")
                val parserValue = value.string("parserValue")
                if (owner == "mindustry.content.Fx" && field != null && parserValue == field && SAFE_PARSER_NAME.matches(field)) {
                    ValueConversion.Mapped(JsonPrimitive(parserValue), kind)
                } else {
                    ValueConversion.Dropped(
                        kind,
                        "RUNTIME_STATIC_REFERENCE_UNMAPPABLE",
                        "Only exact mindustry.content.Fx field identities are accepted (owner=$owner, field=$field, parserValue=$parserValue).",
                    )
                }
            }
            "array" -> {
                val truncated = (value["truncated"] as? JsonPrimitive)?.booleanOrNull
                    ?: return ValueConversion.Dropped(kind, "RUNTIME_TYPED_VALUE_INVALID", "Array has no valid truncated flag.")
                val elementSpec = spec.elementSpec
                    ?: return ValueConversion.Dropped(kind, "RUNTIME_FIELD_KIND_MISMATCH", "This field does not allow an array value.")
                if (truncated) {
                    ValueConversion.Dropped(kind, "RUNTIME_ARRAY_TRUNCATED", "The runtime extractor truncated this collection.")
                } else {
                    val values = value["values"] as? JsonArray
                        ?: return ValueConversion.Dropped(kind, "RUNTIME_TYPED_VALUE_INVALID", "Array has no values list.")
                    val converted = mutableListOf<JsonElement>()
                    values.forEachIndexed { index, child ->
                        when (val childResult = convertTypedValue(child, "$jsonPath.values[$index]", elementSpec)) {
                            is ValueConversion.Mapped -> converted += childResult.value
                            ValueConversion.Null -> converted += JsonNull
                            is ValueConversion.Dropped -> return ValueConversion.Dropped(
                                kind,
                                childResult.code,
                                "Array element $index could not be represented: ${childResult.reason}",
                            )
                        }
                    }
                    ValueConversion.Mapped(JsonArray(converted), kind)
                }
            }
            "opaque" -> ValueConversion.Dropped(
                kind,
                "RUNTIME_FIELD_OPAQUE",
                listOfNotNull(value.string("reason"), value.string("runtimeClass"), value.string("detail")).joinToString(": ")
                    .ifBlank { "Extractor deliberately represented the object as opaque." },
            )
            else -> ValueConversion.Dropped(kind, "RUNTIME_TYPED_VALUE_UNSUPPORTED", "Unsupported typed value kind '$kind'.")
        }
    }

    private fun numberValue(raw: String?, numberType: String?): ValueConversion {
        if (raw == null) return ValueConversion.Dropped("number", "RUNTIME_NUMBER_INVALID", "Number value is missing.")
        val decimal = runCatching { BigDecimal(raw) }.getOrNull()
            ?: return ValueConversion.Dropped("number", "RUNTIME_NUMBER_INVALID", "Non-finite or invalid number '$raw'.")
        return if (numberType in setOf("byte", "short", "int", "long", "bigInteger")) {
            val integer = runCatching { decimal.toBigIntegerExact() }.getOrNull()
                ?: return ValueConversion.Dropped(
                    "number",
                    "RUNTIME_NUMBER_INVALID",
                    "Integer field contains fractional value '$raw'.",
                )
            ValueConversion.Mapped(JsonPrimitive(integer), "number")
        } else {
            ValueConversion.Mapped(JsonPrimitive(decimal), "number")
        }
    }

    private fun collectBehaviorLosses(
        authoritative: JsonObject,
        authoritativeKey: String,
        sourceName: String,
        snapshotPath: Path,
        basePath: String,
        diagnostics: MutableList<Diagnostic>,
    ): Set<String> {
        val codes = linkedSetOf<String>()
        fun stringList(name: String): List<String> = (authoritative[name] as? JsonArray).orEmpty().mapNotNull {
            (it as? JsonPrimitive)?.contentOrNull
        }
        val behaviorGroups = listOf(
            Triple("customFields", "RUNTIME_CUSTOM_FIELD_NOT_SERIALIZED", "Custom Java fields are not part of DataPatcher HJSON."),
            Triple("overriddenMethods", "RUNTIME_OVERRIDDEN_METHOD_NOT_SERIALIZED", "Overridden Java behavior cannot be serialized."),
            Triple("customOnlyMethods", "RUNTIME_CUSTOM_METHOD_NOT_SERIALIZED", "Custom-only Java methods cannot be serialized."),
        )
        behaviorGroups.forEach { (field, code, message) ->
            val values = stringList(field)
            if (values.isNotEmpty()) {
                codes += code
                diagnostics += diagnostic(
                    code = code,
                    severity = DiagnosticSeverity.WARNING,
                    message = "$sourceName: $message",
                    snapshotPath = snapshotPath,
                    jsonPath = "$basePath.runtimeSnapshots.$authoritativeKey.$field",
                    details = values.joinToString("; "),
                    suggestion = "Reimplement only gameplay-relevant behavior with v159.7-supported fields/effects.",
                )
            }
        }
        (authoritative["declaredLosses"] as? JsonArray).orEmpty().forEachIndexed { index, lossElement ->
            val loss = lossElement as? JsonObject ?: return@forEachIndexed
            val code = loss.string("reason")?.takeIf(String::isNotBlank) ?: "RUNTIME_DECLARED_BEHAVIOR_LOSS"
            codes += code
            diagnostics += diagnostic(
                code = code,
                severity = DiagnosticSeverity.WARNING,
                message = "$sourceName: ${loss.string("detail") ?: "The extractor declared an unserializable runtime behavior."}",
                snapshotPath = snapshotPath,
                jsonPath = "$basePath.runtimeSnapshots.$authoritativeKey.declaredLosses[$index]",
                details = loss.string("field"),
            )
        }
        return codes
    }

    private fun collectPhaseDifferences(
        content: JsonObject,
        sourceName: String,
        basePath: String,
        authoritativeKey: String,
        authoritativePhase: String,
        authoritativeFields: JsonObject,
        mappedFields: Set<String>,
        output: MutableList<PhaseDifference>,
    ) {
        val snapshots = content["runtimeSnapshots"] as? JsonObject ?: return
        val phaseOrder = listOf(
            "preContentInit" to "PRE_CONTENT_INIT",
            "postContentInit" to "POST_CONTENT_INIT",
            "finalAfterModInit" to "FINAL_AFTER_MOD_INIT",
        )
        val authoritativeIndex = phaseOrder.indexOfFirst { it.first == authoritativeKey }
        authoritativeFields.forEach { (field, baseline) ->
            if (field !in mappedFields) return@forEach
            val phases = linkedMapOf(authoritativePhase to baseline)
            phaseOrder.drop(authoritativeIndex + 1).forEach { (key, phaseName) ->
                val value = ((snapshots[key] as? JsonObject)?.get("fields") as? JsonObject)?.get(field)
                if (value != null && value != baseline) phases[phaseName] = value
            }
            if (phases.size > 1) {
                output += PhaseDifference(
                    contentName = sourceName,
                    field = field,
                    jsonPath = "$basePath.runtimeSnapshots",
                    phases = phases.map { (phase, value) -> "$phase=${compactTypedValue(value)}" },
                    authoritativePhase = authoritativePhase,
                )
            }
        }
    }

    private fun buildReport(
        snapshotPath: Path,
        jarPath: Path,
        summary: RuntimeSnapshotMappingSummary,
        contentResults: List<RuntimePreparedContentResult>,
        fieldOutcomes: List<FieldOutcome>,
        phaseDifferences: List<PhaseDifference>,
        diagnostics: List<Diagnostic>,
        assetSnapshot: RuntimeAssetSnapshot?,
    ): String {
        val root = buildJsonObject {
            put("schemaVersion", 1)
            put("snapshot", buildJsonObject {
                put("path", snapshotPath.toString())
                put("sha256", sha256(snapshotPath))
                put("runtimeSchemaVersion", summary.snapshotSchemaVersion)
                put("targetMod", summary.targetMod)
            })
            put("releaseJar", buildJsonObject {
                put("path", jarPath.toString())
                put("sha256", sha256(jarPath))
            })
            put("summary", buildJsonObject {
                put("observedContents", summary.observedContents)
                put("convertedContents", summary.convertedContents)
                put("degradedContents", summary.degradedContents)
                put("excludedContents", summary.excludedContents)
                put("unsupportedContents", summary.unsupportedContents)
                put("failedContents", summary.failedContents)
                put("generatedContentFiles", summary.generatedContentFiles)
                put("selectedAssetFiles", summary.selectedAssetFiles)
                put("mappedFields", summary.mappedFields)
                put("omittedNullFields", summary.omittedNullFields)
                put("droppedFields", summary.droppedFields)
                put("infoDiagnostics", diagnostics.count { it.severity == DiagnosticSeverity.INFO })
                put("warningDiagnostics", diagnostics.count { it.severity == DiagnosticSeverity.WARNING })
                put("errorDiagnostics", diagnostics.count { it.severity == DiagnosticSeverity.ERROR })
            })
            put("contents", buildJsonArray {
                contentResults.forEach { result ->
                    add(buildJsonObject {
                        put("sourceSymbol", result.sourceSymbol)
                        result.kind?.let { put("kind", it.name.lowercase(Locale.ROOT)) }
                        put("disposition", result.disposition.name.lowercase(Locale.ROOT))
                        result.sourceType?.let { put("sourceType", it) }
                        result.targetType?.let { put("targetType", it) }
                        result.outputName?.let { put("outputName", it) }
                        result.outputPath?.let { put("outputPath", it) }
                        result.reason?.let { put("reason", it) }
                        put("diagnosticCodes", buildJsonArray {
                            result.diagnosticCodes.forEach { add(JsonPrimitive(it)) }
                        })
                    })
                }
            })
            put("fields", buildJsonArray {
                fieldOutcomes.forEach { outcome ->
                    add(buildJsonObject {
                        put("content", outcome.content)
                        put("field", outcome.field)
                        put("disposition", outcome.disposition.wireName)
                        put("runtimeKind", outcome.runtimeKind)
                        outcome.reason?.let { put("reason", it) }
                        put("snapshotPath", outcome.jsonPath)
                    })
                }
            })
            put("phaseDifferences", buildJsonArray {
                phaseDifferences.forEach { difference ->
                    add(buildJsonObject {
                        put("content", difference.contentName)
                        put("field", difference.field)
                        put("values", buildJsonArray {
                            difference.phases.forEach { add(JsonPrimitive(it)) }
                        })
                    })
                }
            })
            assetSnapshot?.let { assets ->
                put("assets", buildJsonObject {
                    if (assets.resolvedRootPrefix == null) {
                        put("resolvedRootPrefix", JsonNull)
                    } else {
                        put("resolvedRootPrefix", assets.resolvedRootPrefix)
                    }
                    put("scannedEntries", assets.scannedEntryCount)
                    put("candidateFiles", assets.candidateFileCount)
                    put("selectedFiles", assets.files.size)
                    put("selectedBytes", assets.stagedBytes)
                    put("stagingSha256", assets.stagingSha256)
                })
            }
            put("diagnostics", buildJsonArray {
                diagnostics.forEach { diagnostic ->
                    add(buildJsonObject {
                        put("code", diagnostic.code)
                        put("severity", diagnostic.severity.name.lowercase(Locale.ROOT))
                        put("message", diagnostic.message)
                        diagnostic.location?.path?.let { put("path", it) }
                        diagnostic.location?.jsonPath?.let { put("jsonPath", it) }
                        diagnostic.details?.let { put("details", it) }
                        diagnostic.suggestion?.let { put("suggestion", it) }
                    })
                }
            })
        }
        return json.encodeToString(root) + "\n"
    }

