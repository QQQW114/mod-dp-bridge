package io.github.moddpbridge.model

/**
 * One byte-identical official Mindustry release that this project may load, map and validate against.
 *
 * A target is pinned by the SHA-256 of its official `server-release.jar`; nothing else is accepted by the
 * runtime pipeline, because a data pack is only proven against the exact build that produced the runtime
 * snapshot and performed the `DataPatcher.apply` validation.
 *
 * [build] and [revision] are read from the release's own `version.properties`
 * (for example `build=159.7` becomes `build=159, revision=7`). They must match the `gameVersion` block of a
 * retained runtime snapshot and the version rule of every generated declaration.
 */
enum class MindustryTarget(
    val gameVersion: String,
    val build: Int,
    val revision: Int,
    val serverJarSha256: String,
    /** Conventional file name used by this repository's local `work/` layout and launch scripts. */
    val serverJarFileName: String,
    /** Data patch format version accepted by this release (`DataPatcher.patchFormatVersion`). */
    val dataPatchFormatVersion: Int = 2,
) {
    /** Previous production target. Retained so historical evidence and regression fixtures stay reproducible. */
    V159_7(
        gameVersion = "159.7",
        build = 159,
        revision = 7,
        serverJarSha256 = "e41289c32bcf765eb50fa131e6b515d741e20f7843fb567d3aa949e7461f22ab",
        serverJarFileName = "mindustry-v159.7-server-release.jar",
    ),

    /** Current production target for the Saturation Firepower main line. */
    V160_5(
        gameVersion = "160.5",
        build = 160,
        revision = 5,
        serverJarSha256 = "0bd327c6c3d551e7e8fdab7b695517f809baacca3b1f5cb1c1a8dd74836620e0",
        serverJarFileName = "mindustry-v160.5-server-release.jar",
    ),
    ;

    /** Short stable identifier used in reports, metadata and file names. */
    val id: String get() = gameVersion

    val displayName: String get() = "Mindustry v$gameVersion"

    /** Version string as reported by the game itself, for example `160.5`. */
    val versionString: String get() = "$build.$revision"

    override fun toString(): String = "v$gameVersion"

    companion object {
        /** Target generated by default. Keep this in sync with the documented main line. */
        val PRIMARY: MindustryTarget = V160_5

        /** Targets still accepted by `--server-jar`, primary first. */
        val accepted: List<MindustryTarget> = listOf(V160_5, V159_7)

        fun bySha256(sha256: String?): MindustryTarget? =
            sha256?.let { value -> entries.firstOrNull { it.serverJarSha256.equals(value, ignoreCase = true) } }

        fun byBuildRevision(build: Int?, revision: Int?): MindustryTarget? =
            if (build == null || revision == null) null
            else entries.firstOrNull { it.build == build && it.revision == revision }

        fun byId(id: String?): MindustryTarget? =
            id?.let { value -> entries.firstOrNull { it.gameVersion.equals(value, ignoreCase = true) } }

        /** Human-readable list of accepted pins, used in fail-closed error messages. */
        fun pinnedDescription(): String = accepted.joinToString("; ") {
            "${it.displayName} (${it.serverJarSha256})"
        }
    }
}
